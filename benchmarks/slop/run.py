"""Slop benchmark for skills/unslop-academic-writing.

Human baseline: open-access, CC BY abstracts published 2012-2018 (before LLM writing
assistants) from Europe PMC. AI conditions: abstracts generated by `claude -p` for the
same titles, (a) plainly and (b) with the unslop-academic-writing skill in context.

Reports the slop index distribution per condition, AUROC of the linter separating human
from plain-AI text (does the metric detect slop?), and the skill's effect on AI text
(does the skill reduce it toward the human baseline?).

Usage:
    uv run benchmarks/slop/run.py fetch --n 40
    uv run benchmarks/slop/run.py generate --model claude-haiku-4-5-20251001 --limit 20   # paid
    uv run benchmarks/slop/run.py score [--json benchmarks/results/slop.json]
Data is written to benchmarks/slop/data/ (git-ignored; source DOIs are recorded per item).
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import shutil
import statistics
import subprocess
import sys
import urllib.parse
import urllib.request
from pathlib import Path

for _stream in (sys.stdout, sys.stderr):  # Windows consoles default to cp1252
    if hasattr(_stream, "reconfigure"):
        _stream.reconfigure(encoding="utf-8", errors="replace")

ROOT = Path(__file__).resolve().parents[2]
DATA = Path(__file__).with_name("data")
SKILL = ROOT / "skills" / "unslop-academic-writing"
TOPICS = ["neuroscience", "ecology", "machine learning", "cardiology", "materials science", "epidemiology",
          "genomics", "climate", "psychology", "chemistry"]
UA = "research-agent-skills-benchmark/1.0 (https://github.com/KalarisLabs/research-agent-skills)"


def load_slop():
    sys.dont_write_bytecode = True  # never leave __pycache__ inside skills/
    spec = importlib.util.spec_from_file_location("slop_check", SKILL / "scripts" / "slop_check.py")
    mod = importlib.util.module_from_spec(spec)
    sys.modules["slop_check"] = mod
    spec.loader.exec_module(mod)  # type: ignore[union-attr]
    return mod


def read_jsonl(name: str) -> list[dict]:
    p = DATA / name
    if not p.exists():
        return []
    return [json.loads(line) for line in p.read_text(encoding="utf-8").splitlines() if line.strip()]


def write_jsonl(name: str, rows: list[dict]) -> None:
    DATA.mkdir(parents=True, exist_ok=True)
    (DATA / name).write_text("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows), encoding="utf-8")


def cmd_fetch(args: argparse.Namespace) -> int:
    rows, per_topic = [], max(1, args.n // len(TOPICS))
    for topic in TOPICS:
        q = (f'"{topic}" AND OPEN_ACCESS:y AND LICENSE:"cc by" AND PUB_YEAR:[2012 TO 2018] AND HAS_ABSTRACT:y '
             f"AND PUB_TYPE:\"research-article\"")
        url = "https://www.ebi.ac.uk/europepmc/webservices/rest/search?" + urllib.parse.urlencode(
            {"query": q, "resultType": "core", "format": "json", "pageSize": per_topic * 2})
        with urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": UA}), timeout=30) as r:  # noqa: S310
            results = json.loads(r.read().decode("utf-8"))["resultList"]["result"]
        for it in results:
            abstract = " ".join((it.get("abstractText") or "").replace("<", " <").split())
            abstract = __import__("re").sub(r"<[^>]+>", "", abstract).strip()
            if 120 <= len(abstract.split()) <= 350 and it.get("title"):
                rows.append({"topic": topic, "title": it["title"].rstrip("."), "text": abstract,
                             "doi": it.get("doi"), "year": it.get("pubYear"), "license": it.get("license")})
            if sum(r["topic"] == topic for r in rows) >= per_topic:
                break
    write_jsonl("human.jsonl", rows)
    print(f"fetched {len(rows)} human abstracts (CC BY, 2012-2018) -> {DATA / 'human.jsonl'}")
    return 0


def generate(title: str, with_skill: bool, model: str | None) -> str:
    exe = shutil.which("claude")
    if not exe:
        sys.exit("claude CLI not found on PATH")
    prompt = (f"Write the abstract (180-250 words, one paragraph, no title, no preamble) for a research paper "
              f"titled: \"{title}\". Invent plausible specifics; output only the abstract.")
    cmd = [exe, "-p", "--output-format", "json", "--disable-slash-commands", "--tools", "", "--no-session-persistence"]
    if model:
        cmd += ["--model", model]
    if with_skill:
        cmd += ["--append-system-prompt-file", str(SKILL / "SKILL.md")]
    res = subprocess.run(cmd, input=prompt, capture_output=True, text=True, encoding="utf-8", timeout=300)
    return json.loads(res.stdout)["result"].strip()


def cmd_generate(args: argparse.Namespace) -> int:
    human = read_jsonl("human.jsonl")[: args.limit]
    if not human:
        sys.exit("run `fetch` first")
    base, skill = read_jsonl("ai_baseline.jsonl"), read_jsonl("ai_unslop.jsonl")
    done = {r["title"] for r in base} & {r["title"] for r in skill}
    for h in human:
        if h["title"] in done:
            continue
        base.append({"title": h["title"], "text": generate(h["title"], False, args.model), "model": args.model})
        skill.append({"title": h["title"], "text": generate(h["title"], True, args.model), "model": args.model})
        write_jsonl("ai_baseline.jsonl", base)
        write_jsonl("ai_unslop.jsonl", skill)
        print(f"generated {len(base)}/{len(human)}: {h['title'][:60]}")
    return 0


def auroc(pos: list[float], neg: list[float]) -> float:
    """P(score of a random positive > score of a random negative), ties count half."""
    if not pos or not neg:
        return float("nan")
    wins = sum((p > n) + 0.5 * (p == n) for p in pos for n in neg)
    return wins / (len(pos) * len(neg))


def cmd_score(args: argparse.Namespace) -> int:
    slop = load_slop()
    sets = {"human": read_jsonl("human.jsonl"), "ai_baseline": read_jsonl("ai_baseline.jsonl"),
            "ai_unslop": read_jsonl("ai_unslop.jsonl")}
    scores = {k: [slop.analyse(r["text"])["slop_index"] for r in v] for k, v in sets.items()}
    summary: dict = {}
    for k, v in scores.items():
        if v:
            summary[k] = {"n": len(v), "mean": round(statistics.mean(v), 1), "median": round(statistics.median(v), 1),
                          "share_clean_lt5": round(sum(x < 5 for x in v) / len(v), 2)}
            print(f"{k:<12} n={len(v):<3} mean={summary[k]['mean']:<6} median={summary[k]['median']:<6} "
                  f"clean(<5)={summary[k]['share_clean_lt5']:.0%}")
    if scores["human"] and scores["ai_baseline"]:
        summary["auroc_ai_vs_human"] = round(auroc(scores["ai_baseline"], scores["human"]), 3)
        print(f"\nlinter AUROC (plain AI vs human): {summary['auroc_ai_vs_human']}  (0.5 = chance, 1.0 = perfect)")
    if scores["ai_baseline"] and scores["ai_unslop"]:
        b, s = statistics.mean(scores["ai_baseline"]), statistics.mean(scores["ai_unslop"])
        summary["skill_reduction_pct"] = round(100 * (b - s) / b, 1) if b else 0.0
        print(f"skill effect: mean slop index {b:.1f} -> {s:.1f} ({summary['skill_reduction_pct']}% lower)")
    if args.json:
        args.json.parent.mkdir(parents=True, exist_ok=True)
        args.json.write_text(json.dumps(summary, indent=2) + "\n", encoding="utf-8")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    f = sub.add_parser("fetch")
    f.add_argument("--n", type=int, default=40)
    g = sub.add_parser("generate")
    g.add_argument("--model")
    g.add_argument("--limit", type=int, default=20)
    s = sub.add_parser("score")
    s.add_argument("--json", type=Path)
    args = ap.parse_args()
    return {"fetch": cmd_fetch, "generate": cmd_generate, "score": cmd_score}[args.cmd](args)


if __name__ == "__main__":
    sys.exit(main())
