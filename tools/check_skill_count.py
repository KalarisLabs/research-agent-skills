"""Keep every "N skills" claim in the docs equal to the real number of skills.

The count is the number of `skills/*/SKILL.md` files. This script scans the hand-written places that quote it
(README, docs, benchmark docs and graphics, the `[Unreleased]` changelog section) and fails when one disagrees.
Generated files (catalog, llms*.txt, manifests, skills.sh.json, README badge) are checked by
`build_catalog.py --check`; this covers the prose they do not touch.

Skipped on purpose: released changelog sections and security review notes (history), lines quoting an external
snapshot such as the skills.sh install count, and `web/` (generated by its own pipeline).

Usage:
    uv run tools/check_skill_count.py          # report mismatches, exit 1 if any
    uv run tools/check_skill_count.py --fix    # rewrite the mismatched numbers in place
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from common import ROOT, SKILLS_DIR  # noqa: E402

FILES = [
    "README.md",
    "CHANGELOG.md",
    "AGENTS.md",
    "docs/getting-started/quickstart.md",
    "docs/getting-started/index.md",
    "docs/guides/by-field.md",
    "benchmarks/README.md",
    "benchmarks/security_eval/run.py",
    "tools/generate_benchmark_graphics.py",
]
COUNT_RE = re.compile(r"(?<![\d.,])(\d{3})(?=(?:-skill\b|\s+(?:open-source\s+|Agent\s+|research\s+)?skills\b))", re.I)
WINDOW = 40  # only numbers just below the real count are stale totals; "186 skills" is a subset, not the total
EXTERNAL_RE = re.compile(r"installs|stars|downloads", re.I)


def real_count() -> int:
    """Number of skills on disk."""
    return sum(1 for p in SKILLS_DIR.iterdir() if (p / "SKILL.md").is_file())


def is_stale(n: int, count: int) -> bool:
    """True for a number just below the real total (a former total), not a subset size."""
    return count - WINDOW <= n < count


def in_scope(rel: str, lines: list[str]) -> list[int]:
    """Line indexes to scan: all of a file, or only `[Unreleased]` for the changelog."""
    if rel != "CHANGELOG.md":
        return list(range(len(lines)))
    start = next((i for i, ln in enumerate(lines) if ln.startswith("## [Unreleased]")), None)
    if start is None:
        return []
    end = next((i for i in range(start + 1, len(lines)) if lines[i].startswith("## [")), len(lines))
    return list(range(start, end))


def scan(count: int) -> list[tuple[str, int, str, str]]:
    """Return (file, line number, old text, new text) for every stale claim."""
    stale = []
    for rel in FILES:
        path = ROOT / rel
        if not path.is_file():
            continue
        lines = path.read_text(encoding="utf-8").splitlines(keepends=True)
        for i in in_scope(rel, lines):
            line = lines[i]
            if EXTERNAL_RE.search(line) or "skills.sh" in line:
                continue
            fixed = COUNT_RE.sub(lambda m: str(count) if is_stale(int(m.group(1)), count) else m.group(0), line)
            if fixed != line:
                stale.append((rel, i + 1, line.rstrip("\n"), fixed.rstrip("\n")))
    return stale


def main(argv: list[str] | None = None) -> int:
    """Run the command-line interface."""
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--fix", action="store_true", help="rewrite stale numbers in place")
    args = ap.parse_args(argv)
    count = real_count()
    stale = scan(count)
    for rel, n, old, _ in stale:
        print(f"{rel}:{n}: claims a skill count other than {count}: {old.strip()[:110]}")
    if stale and args.fix:
        for rel in sorted({s[0] for s in stale}):
            path = ROOT / rel
            lines = path.read_text(encoding="utf-8").splitlines(keepends=True)
            for r, n, _, new in stale:
                if r == rel:
                    lines[n - 1] = new + ("\n" if lines[n - 1].endswith("\n") else "")
            path.write_text("".join(lines), encoding="utf-8")
        print(f"rewrote {len(stale)} line(s) to {count}")
        return 0
    print(f"{count} skills on disk, {len(stale)} stale claim(s)")
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
